"""Что спросить у поставщика до покупки. Расчет стоит на заявленных цифрах каталога, и каждая из
этих тем может сдвинуть итог: список помогает проверить их в разговоре, а не искать самому.

Вопросы общие для любого решения. Числа расчета (парк, зарядки) подставляем туда, где они есть,
чтобы вопрос был про наш объект, а не вообще.
"""

from __future__ import annotations

from collections.abc import Sequence

from app.schemas.economics import Sizing, SupplierQuestion


def build(sizing: Sizing | None, conditional: Sequence[str] = ()) -> list[SupplierQuestion]:
    """conditional: выбранные роботы, которым задачу склада производитель не подтвердил."""
    fleet = f" и парке в {sizing.fleet} шт." if sizing and sizing.fleet else ""
    chargers = sizing.chargers if sizing else 0
    in_calc = f" В расчете их {chargers}." if chargers else ""
    return [
        *_goods_to_person(conditional),
        SupplierQuestion(
            topic="Зарядка",
            question=(
                f"Сколько зарядных станций нужно при нашей смене{fleet}, как долго робот заряжается "
                f"и можно ли менять батарею на ходу?{in_calc}"
            ),
            why="Число зарядок и время простоя на заряде сдвигают размер парка и вложения",
        ),
        SupplierQuestion(
            topic="Связь с WMS",
            question="Как робот подключается к нашей складской системе: какие интерфейсы, кто делает интеграцию и сколько она стоит?",
            why="Интеграция стоит отдельной статьей вложений, ее цену называет только тот, кто будет делать",
        ),
        SupplierQuestion(
            topic="Сервис",
            question="Кто и за сколько часов приезжает на ремонт, есть ли склад запчастей в России и что входит в абонентское обслуживание?",
            why="Простой робота без сервиса съедает экономию, обслуживание идет в расходы каждый год",
        ),
        SupplierQuestion(
            topic="Сроки",
            question="Через сколько недель после оплаты роботы будут на складе и запущены, из чего складывается этот срок?",
            why="Пока идет запуск, экономии нет, а платить начинаете раньше",
        ),
        SupplierQuestion(
            topic="Обучение",
            question="Кто обучает наших людей, сколько часов это занимает и входит ли обучение в цену?",
            why="Операторов и обучение расчет считает отдельно",
        ),
        SupplierQuestion(
            topic="Гарантия",
            question="Какой срок гарантии, что она покрывает и сколько служит батарея до замены?",
            why="Срок службы и замена батарей влияют на расходы в последние годы горизонта",
        ),
        SupplierQuestion(
            topic="Что входит в цену",
            question="Входит ли в цену НДС, доставка, пусконаладка, программное обеспечение и лицензии на следующие годы?",
            why="Цена в каталоге это цена изделия, без доставки, пусконаладки и интеграции",
        ),
        SupplierQuestion(
            topic="Наш склад",
            question="Подтвердите письменно, что робот проедет по нашему плану: ширина проезда, покрытие пола, уклоны и высота подъема.",
            why="Расчет проверяет это по каталогу, а подтверждение дает только поставщик",
        ),
        SupplierQuestion(
            topic="Пилот",
            question="Можно ли сначала взять один-два робота на пилот и на каких условиях вернуть или докупить остальные?",
            why="Пилот проверяет цифры расчета на вашем складе до большой покупки",
        ),
        SupplierQuestion(
            topic="Сбои",
            question="Что делает робот при потере связи или препятствии на проезде и как быстро склад возвращается к работе вручную?",
            why="Склад не должен вставать, пока чинят робота",
        ),
    ]


def _goods_to_person(robots: Sequence[str]) -> list[SupplierQuestion]:
    """Робот подвозит стеллаж к станции отбора, а производитель в каталоге этого не пишет."""
    if not robots:
        return []
    names = ", ".join(robots)
    return [
        SupplierQuestion(
            topic='Работа "товар к человеку"',
            question=(
                f"{names}: подтвердите, что робот подвозит мобильный стеллаж к станции отбора. Есть ли у вас "
                "программное обеспечение станции, какую массу стеллажа с товаром робот поднимает и сколько "
                "стеллажей в час подвозит одна машина?"
            ),
            why="Каталог этого не подтверждает: без ответа расчет отбора стоит на допущении, что робот так работает",
        )
    ]
