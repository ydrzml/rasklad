import { plural } from "./economicsNames.ts";

/* Почему прогон дал другой парк, чем формула (docs/calculation.md, 1.3). Пик формула берет сама:
   спрос в пиковый час с резервом. Чего в ней нет: рейс она берет по среднему маршруту, без порожних
   переездов (робот отвез паллету или вернул стеллаж и едет за следующим), без очередей и без запаса
   роботов на ремонт. Поэтому прогон дает больше: на Восток-Сервисе цикл 300 с против 202 с по формуле,
   20 роботов в работе и 10% в запасе, всего 23. До 20.10.2026 строка объясняла разницу пиком
   ("в пик спрос 357 в час против 259 в среднем"), хотя формула и так считала эти 357 с резервом */
export function formulaLine(formula: number, fleet: number, kpi: { waiting_share: number }): string {
  const word = (n: number) => `${n} ${plural(n, "робот", "робота", "роботов")}`;
  if (formula === fleet) return `По формуле тоже ${word(formula)}: прогон смены это подтвердил`;
  if (formula > fleet) return `По формуле ${word(formula)}, прогон показал, что хватит ${fleet}: формула берет запас`;
  const queues =
    kpi.waiting_share >= 0.02 ? ` (в этой смене очереди ${Math.round(kpi.waiting_share * 100)}% времени)` : "";
  return (
    `По формуле ${word(formula)}, прогон смены показал ${fleet}: формула берет рейс по среднему маршруту, ` +
    `без порожних переездов, очередей и запаса роботов на ремонт, поэтому дает меньше${queues}`
  );
}
