export function restoreClinicFinance(raw: unknown): ClinicFinance {
  if (!raw || typeof raw !== "object") return {};
  const record = raw as Record<string, unknown>;
  return Object.fromEntries(
    FINANCE_FIELDS.flatMap(({ id, min, max }) => {
      const value = record[id];
      return typeof value === "number" &&
        Number.isFinite(value) &&
        value >= min &&
        value <= max &&
        (!["days_per_year", "rent_service_included", "loan_enabled", "loan_months"].includes(id) ||
          Number.isInteger(value))
        ? [[id, value]]
        : [];
    }),
  );
}
